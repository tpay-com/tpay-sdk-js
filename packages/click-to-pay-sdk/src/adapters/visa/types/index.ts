// ========== Checkout ========================================================

interface VerificationData {
  /** Type of assurance object returned by SRC. */
  verificationType: "CARDHOLDER";
  /**
   * Entity that performed verification.
   * Format: one of the following values:
   * - "02" - SRC Initiator (SRCi)
   * - "03" - SRC Profile/Payment Interface (SRCPI)
   */
  verificationEntity: "02" | "03";
  /**
   * Events that triggered verification.
   * - "01" - Payment transaction
   */
  verificationEvents: "01"[];
  /**
   * Verification method code.
   * - "01" - EMV 3-D Secure ACS
   * - "02" - App-based authentication
   * - "04" - One-time passcode
   * - "07" - FIDO
   */
  verificationMethod: "01" | "02" | "04" | "07";
  /** Verification result code. "01" - Verified. */
  verificationResults: "01";
  /** UTC timestamp in epoch-millis string format. */
  verificationTimestamp: string;
  /** Method-specific result payload (3DS and issuer extensions). */
  methodResults?: Record<string, unknown>;
  transStatus?: "Y" | "R" | "C" | "N" | "U" | "A" | "D" | "I";
  dsTransId?: string;
  acsTransId?: string;
}

/**
 * Information about any risk assessment operations performed by the SRC system.
 */
interface AssuranceData {
  /** Set of verification data structures relating to distinct types of assurance. */
  verificationData: VerificationData[];
  /**
   * Electronic Commerce Indicator (ECI) indicating the result of the authentication.
   * - "05" - Successful authentication
   * - "06" - Authentication attempted
   * - "07" - Authentication not performed
   */
  eci?: "05" | "06" | "07";
}

