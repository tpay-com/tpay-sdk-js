// ========== Shared Types ====================================================

export type JWT = string;

/**
 * Challenge indicator value related to 3DS authentication.
 * Format: one of the following values:
 * - "01" - No preference
 * - "02" - No challenge requested
 * - "03" - Challenge requested (3DS Requestor Preference)
 * - "04" - Challenge requested (Mandate)
 * - "05" - No challenge requested (transactional risk analysis already performed)
 * - "06" - No challenge requested (data share only)
 * - "07" - No challenge requested (strong consumer authentication already performed)
 * - "08" - No challenge requested (use trust list exemption if no challenge required)
 * - "09" - Challenge requested (trust list prompt requested if challenge required)
 */
type ChallengeIndicator =
  | "01"
  | "02"
  | "03"
  | "04"
  | "05"
  | "06"
  | "07"
  | "08"
  | "09";

/**
 * Action code indicating the next step required by the DCF (Digital Card Facility).
 */
type DcfActionCode =
  | "COMPLETE"
  | "CHANGE_CARD"
  | "ADD_CARD"
  | "SWITCH_CONSUMER"
  | "CANCEL"
  | "ERROR";

/**
 * Represents the current status of the card in the SRC system.
 */
type CardStatus = "ACTIVE" | "SUSPENDED" | "EXPIRED" | "PENDING" | "CANCELLED";

